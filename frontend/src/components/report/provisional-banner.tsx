import { BadgeCheck, ShieldAlert } from "lucide-react";
import type { ReleaseInfo, RubricRef } from "@/lib/types";
import { cn } from "@/lib/utils";
import { fmtIST } from "./format";
import { rubricLabel } from "./use-rubric";

/** "PROVISIONAL: AI first-pass marks against rubric X v1 (AUTHOR_DRAFT). ..." */
export function releaseText(release: ReleaseInfo, rubric: RubricRef): string {
  if (release.status === "RELEASED") {
    const who = release.reviewed_by ?? "faculty";
    return `Released by ${who}${release.reviewed_at ? ` on ${fmtIST(release.reviewed_at)}` : ""}. Marks against rubric ${rubricLabel(rubric)} (${rubric.status}).`;
  }
  return `PROVISIONAL: AI first-pass marks against rubric ${rubricLabel(rubric)} (${rubric.status}). Teacher review pending. Not official NEET scoring. Model-rubric agreement is not faculty certification.`;
}

/** Banner under the report header, driven by the release gate and the rubric status. */
export function ProvisionalBanner({
  release,
  rubric,
  isDemo,
}: {
  release: ReleaseInfo;
  rubric: RubricRef;
  isDemo: boolean;
}) {
  const released = release.status === "RELEASED";
  return (
    <div
      role="note"
      className={cn(
        "flex items-start gap-3 rounded-xl border-l-4 px-4 py-3 text-sm leading-relaxed [print-color-adjust:exact]",
        released
          ? "border-brand-lime-600 bg-brand-lime-50 text-lime-950"
          : "border-rose-400 bg-rose-50 font-medium text-rose-900",
      )}
    >
      {released ? (
        <BadgeCheck className="mt-0.5 h-4 w-4 shrink-0 text-lime-700" aria-hidden />
      ) : (
        <ShieldAlert className="mt-0.5 h-4 w-4 shrink-0 text-rose-600" aria-hidden />
      )}
      <p>
        {releaseText(release, rubric)}
        {released && release.note ? <span className="block text-xs font-normal">Reviewer note: {release.note}</span> : null}
        {isDemo ? (
          <span className="mt-0.5 block text-xs font-normal opacity-90">
            Synthetic demo record - no source scan, no AI call; marks are generated by the demo seeder.
          </span>
        ) : null}
      </p>
    </div>
  );
}

/** Quoted CSS string for `content:` (escapes backslashes, quotes and line breaks). */
function cssString(text: string): string {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/[\r\n]+/g, " ")}"`;
}

/**
 * Print-only running footer with the banner text and run id. It is drawn in the bottom page-margin
 * box (`@page { @bottom-center }`), so it repeats on every printed page without covering body text;
 * the page counter sits in @bottom-right (globals.css). A plain footer line closes the report too,
 * for browsers without page-margin boxes.
 */
export function PrintFooter({ text, runId }: { text: string; runId: string }) {
  const line = `3i Academic Intelligence • ${text} • ${runId}`;
  const rule =
    `@page { @bottom-center { content: ${cssString(line)}; font-family: ui-sans-serif, system-ui, sans-serif; ` +
    "font-size: 7pt; line-height: 1.3; color: #475569; vertical-align: middle; } }";
  return (
    <>
      <style>{rule}</style>
      <p className="sair-print-only border-t border-slate-300 pt-2 text-center text-[10px] leading-snug text-slate-500">
        {line}
      </p>
    </>
  );
}
